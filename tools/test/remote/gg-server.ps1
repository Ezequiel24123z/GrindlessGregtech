function Get-GGList {
    param($Value)
    return @(@($Value) | Where-Object { $null -ne $_ -and "$_" -ne '' })
}

function Write-GGServerProperties {
    param([string]$Path, $Req, [int]$Port, [int]$RconPort, [string]$RconPassword)
    $p = [ordered]@{}
    $p['server-ip'] = '127.0.0.1'
    $p['server-port'] = [string]$Port
    $p['online-mode'] = 'false'
    $p['level-seed'] = [string]$Req.seed
    $p['level-type'] = $(if ($Req.flat) { 'minecraft\:flat' } else { 'minecraft\:normal' })
    $p['view-distance'] = '4'
    $p['simulation-distance'] = '4'
    $p['spawn-protection'] = '0'
    $p['max-tick-time'] = '-1'
    $p['enable-rcon'] = 'true'
    $p['rcon.port'] = [string]$RconPort
    $p['rcon.password'] = $RconPassword
    $p['broadcast-rcon-to-ops'] = 'false'
    $p['enforce-secure-profile'] = 'false'
    $p['motd'] = 'GG test server'
    $p['max-players'] = '4'
    foreach ($kv in (Get-GGList $Req.serverProps)) {
        if ($kv -match '^\s*([^=\s]+)\s*=(.*)$') { $p[$Matches[1]] = $Matches[2] }
    }
    $lines = @('#Generated by the Gregtech Grindless test harness')
    foreach ($k in $p.Keys) { $lines += ('{0}={1}' -f $k, $p[$k]) }
    [IO.File]::WriteAllLines($Path, [string[]]$lines, (New-Object Text.UTF8Encoding($false)))
}

function Get-GGFailureHint {
    param([string]$ResDir, [string]$Instance)
    $bits = @()
    $crash = Join-Path $Instance 'crash-reports'
    if (Test-Path $crash) {
        $reports = @(Get-ChildItem $crash -File -ErrorAction SilentlyContinue | Sort-Object LastWriteTime -Descending)
        if ($reports.Count -gt 0) {
            $bits += ('crash report ' + $reports[0].Name + ': ' + (Get-GGCrashHint $reports[0].FullName))
            if ($reports.Count -gt 1) { $bits += ('(+{0} more crash report(s))' -f ($reports.Count - 1)) }
        }
    }
    if ($bits.Count -eq 0) {
        foreach ($f in @('server-stderr.log', 'server-stdout.log')) {
            $path = Join-Path $ResDir $f
            if (Test-Path $path) {
                $t = @(Get-Content -LiteralPath $path -Tail 400 -ErrorAction SilentlyContinue | Where-Object { $_ -match '(?i)error|exception|fatal|caused by|failed' -and $_ -notmatch '^\s*at ' } | Select-Object -Last 5)
                if ($t.Count -gt 0) { $bits += ($f + ': ' + (($t | ForEach-Object { $_.Trim() }) -join ' / ')); break }
            }
        }
    }
    return ($bits -join '; ')
}

# ---- post-boot settle -----------------------------------------------------------------------------------------------
# Some mods (Additional Placements) reload the datapacks a few seconds after "Done"; that re-runs the KubeJS server
# scripts and wipes whatever a test started right away. The settle stage reads the log after "Done" with these helpers:
#   start of a reload  : "Reloading!" (vanilla /reload message), any line saying "reloading" (e.g. "reloading datapacks")
#                        or KubeJS re-running its server scripts / recipe event (also true for a silent reload)
#   end of a reload    : KubeJS "Server resource reload complete!" / "Reloaded with no KubeJS errors!"
#   reload activity    : the lines a reload prints while it works (recipes, tags, advancements)

function New-GGSettleState {
    return @{ AfterDone = $false; Open = $false; Reloads = 0; LastAct = $null; Events = (New-Object System.Collections.ArrayList) }
}

# Feeds one log line, seen T seconds into the settle, to the state. Returns a message when a reload starts or ends.
function Add-GGSettleLine {
    param($S, [string]$Line, [double]$T)
    if (-not $S.AfterDone) {
        if ($Line -match 'Done \([\d.,]+s\)! For help, type "help"') { $S.AfterDone = $true }
        return ''
    }
    $show = $Line
    if ($show.Length -gt 160) { $show = $show.Substring(0, 160) }
    if ($Line -match '(?i)resource reload complete|\breloaded\b') {
        $msg = ''
        if ($S.Open) { $msg = ('reload finished +{0:N1}s' -f $T) }
        $S.Open = $false
        $S.LastAct = $T
        [void]$S.Events.Add(('+{0:N1}s end   {1}' -f $T, $show))
        return $msg
    }
    if ($Line -match '(?i)\breloading\b|Loaded \d+/\d+ KubeJS server scripts|Initializing recipe event') {
        # KubeJS reloads its server scripts first on EVERY reload, even a silent one that logs no "Reloading!" line
        $msg = ''
        if (-not $S.Open) { $S.Reloads++; $msg = ('datapack reload detected +{0:N1}s: {1}' -f $T, $show) }
        $S.Open = $true
        $S.LastAct = $T
        [void]$S.Events.Add(('+{0:N1}s start {1}' -f $T, $show))
        return $msg
    }
    if ($Line -match '(?i)Processing recipes|Posted recipe events|Clearing KubeJS recipe lists|Loaded \d+ advancements|Found \d+ recipes|Added \d+ recipes|\] Found \d+ tags') {
        $S.LastAct = $T
    }
    return ''
}

# '' = keep waiting; otherwise 'quiet' (settled), 'noend' (reload announced, never reported complete) or 'cap'.
function Get-GGSettleVerdict {
    param($S, [double]$T, [double]$MinSec, [double]$QuietSec, [double]$GraceSec, [double]$CapSec)
    $quiet = $T
    if ($null -ne $S.LastAct) { $quiet = $T - $S.LastAct }
    if ($T -ge $MinSec) {
        if (-not $S.Open -and $quiet -ge $QuietSec) { return 'quiet' }
        if ($S.Open -and $quiet -ge $GraceSec) { return 'noend' }
    }
    if ($T -gt $CapSec) { return 'cap' }
    return ''
}

# ---- a bounded restart inside one run: the command `@restart:<marker regex>[&&<marker regex>...]` -----------------------------------
# For a test that must see a cold start of the same world (persistent data, chunks and machines read back from disk). It waits until every
# marker has appeared in the server's logs (at most min(180 s, waitTimeoutSec)): in a run with other tests, list their DONE markers too, so
# the restart ends none of them halfway. Then it stops the server through its console (the final shutdown's 30 s grace; it must exit 0,
# i.e. after saving), keeps the first boot's logs in results\server\phase1\ and starts the same command line (same heap) on the same world,
# then waits for Done, the same post-boot settle and RCON. The run keeps its slot and the global Minecraft mutex throughout, so this is still
# the one test JVM; every wait runs on the run's one native budget clock (never reset: a restart spends the same 600 s), and a run holds at
# most one restart, server suite only (Assert-GGResourceRequest).
function Invoke-GGServerRestart {
    param($Ctx, [string]$Inst, [string]$Res, $Req, [string]$Marker)
    $budget = $global:GG.NativeBudget
    if (-not $budget) { throw 'restart before the first boot: there is no native budget clock' }

    $patterns = @()
    if ($Marker) { $patterns = @($Marker -split '&&') }
    if ($patterns.Count -gt 0) {
        $rxs = @($patterns | ForEach-Object { New-Object Text.RegularExpressions.Regex($_) })
        $seen = @($rxs | ForEach-Object { $false })
        $limitMs = Get-GGNativeTimeoutMs $budget ([math]::Min(180, [int]$Req.waitTimeoutSec) * 1000)
        $tails = @((New-Object GGTail (Join-Path $Inst 'logs\kubejs\server.log')), (New-Object GGTail (Join-Path $Inst 'logs\latest.log')))
        $sw = [Diagnostics.Stopwatch]::StartNew()
        while ($true) {
            [void](Get-GGNativeTimeoutMs $budget 1)
            foreach ($t in $tails) {
                foreach ($l in $t.ReadNew()) {
                    for ($i = 0; $i -lt $rxs.Count; $i++) { if (-not $seen[$i] -and $rxs[$i].IsMatch($l)) { $seen[$i] = $true } }
                }
            }
            $open = @(for ($i = 0; $i -lt $rxs.Count; $i++) { if (-not $seen[$i]) { $patterns[$i] } })
            if ($open.Count -eq 0) { break }
            if ($Ctx.Proc.HasExited) { throw ("the server exited (code {0}) before the restart marker(s) [{1}]" -f $Ctx.Proc.ExitCode, ($open -join '] [')) }
            if ($sw.Elapsed.TotalMilliseconds -gt $limitMs) { throw ("restart marker(s) [{0}] not seen within {1}s" -f ($open -join '] ['), [int]($limitMs / 1000)) }
            Update-GGLock
            Start-Sleep -Milliseconds 500
        }
        Write-GGLog ("  restart marker hit [{0}] after {1}s" -f ($patterns -join '] ['), [int]$sw.Elapsed.TotalSeconds)
    }

    # clean stop, as the final shutdown does: the console's `stop`, 30 s at most, exit code 0 (the world and persistent data saved)
    if ($Ctx.Rcon) { $Ctx.Rcon.Dispose(); $Ctx.Rcon = $null }
    $g = $Ctx.Proc
    $g.WriteLine('stop')
    $stopMs = Get-GGNativeTimeoutMs $budget 30000
    if (-not $g.WaitForExit($stopMs)) { throw ("the server did not stop within {0}s for the restart" -f [int]($stopMs / 1000)) }
    $g.CloseLogs()
    Set-GGSlotState $null $false
    if ($g.ExitCode -ne 0) { throw ("the server stopped with exit code {0} for the restart (not a clean save)" -f $g.ExitCode) }
    $Ctx.Booted = $false

    # the first boot's logs go to results\server\phase1\ and leave the instance, so the second boot's waits only read the second boot
    $keep = Join-Path $Res 'phase1'
    New-Item -ItemType Directory -Force -Path (Join-Path $keep 'logs\kubejs') | Out-Null
    foreach ($rel in @('logs\latest.log', 'logs\debug.log')) {
        $src = Join-Path $Inst $rel
        if (Test-Path -LiteralPath $src) { Move-Item -LiteralPath $src -Destination (Join-Path $keep $rel) -Force }
    }
    Get-ChildItem (Join-Path $Inst 'logs\kubejs') -Filter *.log -File -ErrorAction SilentlyContinue | ForEach-Object {
        Move-Item -LiteralPath $_.FullName -Destination (Join-Path $keep ('logs\kubejs\' + $_.Name)) -Force
    }
    foreach ($f in @('server-stdout.log', 'server-stderr.log')) {
        $src = Join-Path $Res $f
        if (Test-Path -LiteralPath $src) { Move-Item -LiteralPath $src -Destination (Join-Path $keep $f) -Force }
    }
    $Ctx.Phase1Logs = $true

    # the same command line on the same world (no RAM gate: the one global test JVM and its heap caps are the limits)
    [void](Get-GGNativeTimeoutMs $budget 1)
    $argLine = "-Dgg.run=$($global:GG.RunId) @user_jvm_args.txt @libraries/net/minecraftforge/forge/$($Ctx.ForgeVer)/win_args.txt nogui"
    $g2 = [GGProc]::Start($Ctx.Java, $argLine, $Inst, (Join-Path $Res 'server-stdout.log'), (Join-Path $Res 'server-stderr.log'), $null)
    $Ctx.Proc = $g2
    Set-GGSlotState $null $true
    Write-GGLog "server JVM restarted on the same world (pid $($g2.Id))"

    $tail = New-Object GGTail (Join-Path $Inst 'logs\latest.log')
    $doneRx = [regex]'Done \(([\d.,]+)s\)! For help, type "help"'
    $sw = [Diagnostics.Stopwatch]::StartNew()
    $bootSecs = $null
    while (-not $bootSecs) {
        [void](Get-GGNativeTimeoutMs $budget 1)
        foreach ($l in $tail.ReadNew()) { $m = $doneRx.Match($l); if ($m.Success) { $bootSecs = $m.Groups[1].Value } }
        if ($bootSecs) { break }
        if ($g2.HasExited) { throw ("the restarted server exited with code {0} before 'Done' after {1}s. {2}" -f $g2.ExitCode, [int]$sw.Elapsed.TotalSeconds, (Get-GGFailureHint $Res $Inst)) }
        if ($sw.Elapsed.TotalSeconds -gt [int]$Req.bootTimeoutSec) { throw ("the restarted server did not boot within {0}s" -f $Req.bootTimeoutSec) }
        Update-GGLock
        Start-Sleep -Milliseconds 1000
    }
    $Ctx.Booted = $true
    Write-GGLog ("  restarted: Done in {0}s (wall {1}s)" -f $bootSecs, [int]$sw.Elapsed.TotalSeconds)

    # the same post-boot settle as the first boot (a datapack reload re-runs the KubeJS server scripts)
    $minSettle = 15
    if ($null -ne $Req.settleSec) { $minSettle = [int]$Req.settleSec }
    if ($minSettle -gt 0) {
        $state = New-GGSettleState
        $settleTail = New-Object GGTail (Join-Path $Inst 'logs\latest.log')
        $ssw = [Diagnostics.Stopwatch]::StartNew()
        $verdict = ''
        while (-not $verdict) {
            [void](Get-GGNativeTimeoutMs $budget 1)
            foreach ($l in $settleTail.ReadNew()) { [void](Add-GGSettleLine $state $l $ssw.Elapsed.TotalSeconds) }
            if ($g2.HasExited) { throw ("the restarted server exited during its settle (code {0})" -f $g2.ExitCode) }
            $verdict = Get-GGSettleVerdict $state $ssw.Elapsed.TotalSeconds $minSettle 4 30 ($minSettle + 240)
            if (-not $verdict) { Update-GGLock; Start-Sleep -Milliseconds 500 }
        }
        Write-GGLog ("  restarted: settled {0:N1}s after Done ({1}, {2} datapack reload(s))" -f $ssw.Elapsed.TotalSeconds, $verdict, $state.Reloads)
    }

    $deadline = (Get-Date).AddSeconds(90)
    while ($true) {
        $connectTimeout = Get-GGNativeTimeoutMs $budget 10000
        try {
            $Ctx.Rcon = [GGRcon]::Connect('127.0.0.1', $Ctx.RconPort, $Ctx.RconPw, $connectTimeout)
            break
        } catch {
            if ((Get-Date) -gt $deadline) { throw ("RCON connect after the restart failed: {0}" -f $_.Exception.Message) }
            if ($g2.HasExited) { throw ("the restarted server exited while waiting for RCON (code {0})" -f $g2.ExitCode) }
            Start-Sleep -Seconds 2
        }
    }
    $Ctx.Restarted = $true
    Write-GGLog '  restarted: RCON connected again'
}

function Invoke-GGServerSuite {
    param($Req, [string]$PackToml, $PackInfo, [string]$PackKey)

    $res = Join-Path $global:GG.ResultsDir 'server'
    $inst = Join-Path $global:GG.RunDir 'server'
    $overlay = Join-Path $global:GG.RunDir 'overlay'
    New-Item -ItemType Directory -Force -Path $res | Out-Null

    $commands = @(Get-GGList $Req.commands)
    $waits = @(Get-GGList $Req.waitForLog)
    $bootTimeout = [int]$Req.bootTimeoutSec
    $cmdTimeout = [int]$Req.commandTimeoutSec
    $ctx = @{ Proc = $null; Rcon = $null; Java = ''; ForgeVer = ''; Port = 0; RconPort = 0; RconPw = ''; ExpectStop = $false; Booted = $false; Restarted = $false; Phase1Logs = $false }
    foreach ($c in $commands) { if ($c -match '^\s*/?stop\s*$') { $ctx.ExpectStop = $true } }

    try {
        $ok = Invoke-GGStage 'forge-server' {
            $f = Ensure-GGForgeServer $PackInfo.mc $PackInfo.forge
            $ctx.ForgeVer = $f.Ver
            $ctx.Java = Get-GGJava17
            Remove-GGTree $inst
            Copy-GGTree $f.Dir $inst
            $how = 'installed'
            if ($f.Cached) { $how = 'cached' }
            Set-GGStage 'PASS' ("forge {0} ({1})" -f $f.Ver, $how)
        }

        if ($ok) {
            $ok = Invoke-GGStage 'sync-server' {
                $how = Ensure-GGInstaller
                # the sync dir is shared by every run of this pack: one run at a time may update it and copy from it
                Invoke-GGExclusive "sync-$PackKey-server" {
                    $sync = Sync-GGPack 'server' $PackToml $PackKey $res
                    Copy-GGTree $sync $inst @() @('packwiz.json')
                }
                $n = @(Get-ChildItem (Join-Path $inst 'mods') -Filter *.jar -File -ErrorAction SilentlyContinue).Count
                $mb = Get-GGDirSizeMB (Join-Path $inst 'mods')
                Set-GGStage 'PASS' ("{0} mod jars, {1} MB (installer {2})" -f $n, $mb, $how)
            }
        }

        if ($ok) {
            $ok = Invoke-GGStage 'overlay' {
                $rel = @(Add-GGOverlay $overlay $inst)
                [IO.File]::WriteAllLines((Join-Path $res 'overlay-files.txt'), [string[]]$rel)
                foreach ($w in @('world', 'world_nether', 'world_the_end')) { Remove-GGTree (Join-Path $inst $w) }
                $ctx.Port = Get-GGSlotPort 'server'
                $ctx.RconPort = Get-GGSlotPort 'rcon'
                $ctx.RconPw = ([guid]::NewGuid().ToString('N')).Substring(0, 20)
                Set-Content -LiteralPath (Join-Path $inst 'eula.txt') -Value 'eula=true' -Encoding ASCII
                Write-GGServerProperties (Join-Path $inst 'server.properties') $Req $ctx.Port $ctx.RconPort $ctx.RconPw
                $jvm = @("-Xms$($Req.serverXms)", "-Xmx$($Req.serverXmx)", '-Dfile.encoding=UTF-8')
                [IO.File]::WriteAllLines((Join-Path $inst 'user_jvm_args.txt'), [string[]]$jvm, (New-Object Text.UTF8Encoding($false)))
                Set-GGStage 'PASS' ("{0} overlay file(s); fresh world; ports {1}/{2}" -f $rel.Count, $ctx.Port, $ctx.RconPort)
            }
        }

        if ($ok) {
            $ok = Invoke-GGStage 'boot' {
                if (-not $global:GG.NativeBudget) { $global:GG.NativeBudget = @{ Clock = [Diagnostics.Stopwatch]::StartNew(); TimeoutSec = [int]$Req.nativeTimeoutSec } }
                [void](Get-GGNativeTimeoutMs $global:GG.NativeBudget 1)
                # -Dgg.run names the run in the JVM's command line (the other arguments are relative), so JVMs of a dead run can be told apart from the other slot's
                $argLine = "-Dgg.run=$($global:GG.RunId) @user_jvm_args.txt @libraries/net/minecraftforge/forge/$($ctx.ForgeVer)/win_args.txt nogui"
                $g = [GGProc]::Start($ctx.Java, $argLine, $inst, (Join-Path $res 'server-stdout.log'), (Join-Path $res 'server-stderr.log'), $null)
                $ctx.Proc = $g
                Set-GGSlotState $null $true
                Write-GGLog "server JVM started (pid $($g.Id))"
                $tail = New-Object GGTail (Join-Path $inst 'logs\latest.log')
                $doneRx = [regex]'Done \(([\d.,]+)s\)! For help, type "help"'
                $sw = [Diagnostics.Stopwatch]::StartNew()
                $bootSecs = $null
                $lastLine = ''
                $lastPrint = 0
                while ($true) {
                    [void](Get-GGNativeTimeoutMs $global:GG.NativeBudget 1)
                    $exited = $g.HasExited
                    foreach ($l in $tail.ReadNew()) {
                        $lastLine = $l
                        $m = $doneRx.Match($l)
                        if ($m.Success) { $bootSecs = $m.Groups[1].Value }
                    }
                    if ($bootSecs) { break }
                    if ($exited) {
                        $hint = Get-GGFailureHint $res $inst
                        throw ("server exited with code {0} before 'Done' after {1}s. {2}" -f $g.ExitCode, [int]$sw.Elapsed.TotalSeconds, $hint)
                    }
                    if ($sw.Elapsed.TotalSeconds -gt $bootTimeout) {
                        $hint = Get-GGFailureHint $res $inst
                        throw ("boot timed out after {0}s; last log line: {1} {2}" -f $bootTimeout, $lastLine, $hint)
                    }
                    if ($sw.Elapsed.TotalSeconds - $lastPrint -ge 30) {
                        $lastPrint = $sw.Elapsed.TotalSeconds
                        $show = $lastLine
                        if ($show.Length -gt 150) { $show = $show.Substring(0, 150) }
                        Write-GGLog ("  booting {0}s | {1}" -f [int]$sw.Elapsed.TotalSeconds, $show)
                    }
                    Update-GGLock
                    Start-Sleep -Milliseconds 1000
                }
                Set-GGStage 'PASS' ("Done in {0}s (wall {1}s)" -f $bootSecs, [int]$sw.Elapsed.TotalSeconds)
                $ctx.Booted = $true
            }
        }

        if ($ok) {
            # Mods such as Additional Placements reload the datapacks a few seconds after "Done". That re-runs the KubeJS
            # server scripts and wipes anything a test started right away, so commands only run once the server is idle.
            $ok = Invoke-GGStage 'settle' {
                $minSettle = 15
                if ($null -ne $Req.settleSec) { $minSettle = [int]$Req.settleSec }
                if ($minSettle -le 0) { Set-GGStage 'SKIP' 'disabled (-SettleSec 0)'; return }
                $quietSec = 4      # no reload activity for this long ...
                $graceSec = 30     # ... or, if a reload was announced but never reported complete, this long
                $capSec = $minSettle + 240
                $tail = New-Object GGTail (Join-Path $inst 'logs\latest.log')
                $state = New-GGSettleState
                $verdict = ''
                $sw = [Diagnostics.Stopwatch]::StartNew()
                while ($true) {
                    [void](Get-GGNativeTimeoutMs $global:GG.NativeBudget 1)
                    $exited = $ctx.Proc.HasExited
                    foreach ($l in $tail.ReadNew()) {
                        $msg = Add-GGSettleLine $state $l $sw.Elapsed.TotalSeconds
                        if ($msg) { Write-GGLog "  $msg" }
                    }
                    if ($exited) {
                        $hint = Get-GGFailureHint $res $inst
                        throw ("server exited during the post-boot settle (code {0}). {1}" -f $ctx.Proc.ExitCode, $hint)
                    }
                    $verdict = Get-GGSettleVerdict $state $sw.Elapsed.TotalSeconds $minSettle $quietSec $graceSec $capSec
                    if ($verdict) { break }
                    Update-GGLock
                    Start-Sleep -Milliseconds 500
                }
                $secs = $sw.Elapsed.TotalSeconds
                [IO.File]::WriteAllLines((Join-Path $res 'settle.txt'), [string[]]@($state.Events.ToArray()))
                $what = 'no datapack reload seen'
                if ($state.Reloads -gt 0) { $what = "{0} datapack reload(s) seen, last activity +{1:N1}s" -f $state.Reloads, $state.LastAct }
                if ($verdict -eq 'cap') {
                    Set-GGStage 'WARN' ("gave up after {0:N1}s: a datapack reload was still running; commands may be wiped by it" -f $secs)
                } else {
                    $note = ''
                    if ($verdict -eq 'noend') { $note = "; a 'Reloading' line was never followed by a completion line" }
                    Set-GGStage 'PASS' ("settled {0:N1}s after Done ({1}{2})" -f $secs, $what, $note)
                }
            }
        }

        if ($ok) {
            [void](Invoke-GGStage 'rcon' {
                    $deadline = (Get-Date).AddSeconds(90)
                    $lastErr = ''
                    while ($true) {
                        $connectTimeout = Get-GGNativeTimeoutMs $global:GG.NativeBudget 10000
                        try {
                            $ctx.Rcon = [GGRcon]::Connect('127.0.0.1', $ctx.RconPort, $ctx.RconPw, $connectTimeout)
                            break
                        } catch {
                            $lastErr = $_.Exception.Message
                            if ((Get-Date) -gt $deadline) { throw "RCON connect failed: $lastErr" }
                            if ($ctx.Proc.HasExited) { throw "server exited while waiting for RCON (code $($ctx.Proc.ExitCode))" }
                            Start-Sleep -Seconds 2
                        }
                    }
                    Set-GGStage 'PASS' ("connected on 127.0.0.1:{0}" -f $ctx.RconPort)
                })
        }

        if ($ok -and $commands.Count -gt 0) {
            [void](Invoke-GGStage 'commands' {
                    if (-not $ctx.Rcon) { throw 'no RCON connection' }
                    $rlog = Join-Path $res 'rcon.log'
                    $bad = @()
                    $i = 0
                    foreach ($c in $commands) {
                        $commandBudget = Get-GGNativeTimeoutMs $global:GG.NativeBudget ($cmdTimeout * 1000)
                        $i++
                        if ($c -match '^@restart(?::(.+))?$') {
                            # not an RCON command: the harness's bounded restart (one per run, same budget; see Invoke-GGServerRestart)
                            Write-GGLog "restart> $c"
                            Invoke-GGServerRestart $ctx $inst $res $Req ([string]$Matches[1])
                            continue
                        }
                        if ([Text.Encoding]::UTF8.GetByteCount($c) -gt 1440) { $bad += "#$i too long (>1440 bytes)"; continue }
                        Write-GGLog "rcon> $c"
                        $t0 = Get-Date
                        $reply = $null
                        try {
                            $reply = $ctx.Rcon.Command($c, $commandBudget)
                        } catch {
                            $err = $_.Exception.Message
                            if ($ctx.Proc.HasExited) { $bad += "#$i '$c': server died ($err)"; break }
                            $bad += "#$i '$c': $err"
                            $connectTimeout = Get-GGNativeTimeoutMs $global:GG.NativeBudget 10000
                            try { $ctx.Rcon.Dispose(); $ctx.Rcon = [GGRcon]::Connect('127.0.0.1', $ctx.RconPort, $ctx.RconPw, $connectTimeout) } catch { break }
                            continue
                        }
                        $secs = ((Get-Date) - $t0).TotalSeconds
                        [IO.File]::AppendAllText($rlog, ("[{0}] > {1}`r`n{2}`r`n`r`n" -f (Get-Date).ToString('HH:mm:ss'), $c, $reply))
                        $show = ($reply -replace '\s+', ' ').Trim()
                        if ($show.Length -gt 300) { $show = $show.Substring(0, 300) + '...' }
                        Write-GGLog ("  <  ({0:N1}s) {1}" -f $secs, $show)
                        if ($reply -match 'Unknown or incomplete command|^Unknown command|Error executing|<--\[HERE\]') { $bad += "#$i '$c': $show" }
                    }
                    if ($bad.Count -gt 0) { throw ("{0}/{1} command(s) failed: {2}" -f $bad.Count, $commands.Count, ($bad -join ' | ')) }
                    Set-GGStage 'PASS' ("{0}/{0} command(s) ok" -f $commands.Count)
                })
        }

        if ($ok -and $waits.Count -gt 0) {
            [void](Invoke-GGStage 'wait-markers' {
                    $pending = @()
                    foreach ($w in $waits) {
                        $to = [int]$w.timeoutSec
                        if ($to -le 0) { $to = [int]$Req.waitTimeoutSec }
                        $pending += @{ Pattern = [string]$w.pattern; Rx = (New-Object Text.RegularExpressions.Regex([string]$w.pattern)); Timeout = $to; Hit = $null }
                    }
                    $tails = @(
                        @{ Name = 'kubejs/server.log'; Tail = (New-Object GGTail (Join-Path $inst 'logs\kubejs\server.log')) },
                        @{ Name = 'latest.log'; Tail = (New-Object GGTail (Join-Path $inst 'logs\latest.log')) }
                    )
                    $sw = [Diagnostics.Stopwatch]::StartNew()
                    $lastPrint = 0
                    while ($true) {
                        [void](Get-GGNativeTimeoutMs $global:GG.NativeBudget 1)
                        $exited = $ctx.Proc.HasExited
                        foreach ($t in $tails) {
                            foreach ($line in $t.Tail.ReadNew()) {
                                foreach ($p in $pending) {
                                    if (-not $p.Hit -and $p.Rx.IsMatch($line)) {
                                        $p.Hit = ('{0}: {1}' -f $t.Name, $line)
                                        Write-GGLog ("  marker hit [{0}] after {1}s" -f $p.Pattern, [int]$sw.Elapsed.TotalSeconds)
                                    }
                                }
                            }
                        }
                        $open = @($pending | Where-Object { -not $_.Hit })
                        if ($open.Count -eq 0) { break }
                        $expired = @($open | Where-Object { $sw.Elapsed.TotalSeconds -gt $_.Timeout })
                        if ($exited -or $expired.Count -eq $open.Count) { break }
                        if ($sw.Elapsed.TotalSeconds - $lastPrint -ge 30) {
                            $lastPrint = $sw.Elapsed.TotalSeconds
                            Write-GGLog ("  waiting for {0} marker(s), {1}s" -f $open.Count, [int]$sw.Elapsed.TotalSeconds)
                        }
                        Update-GGLock
                        Start-Sleep -Milliseconds 1000
                    }
                    $missing = @($pending | Where-Object { -not $_.Hit })
                    $rep = @($pending | ForEach-Object { if ($_.Hit) { 'HIT  ' + $_.Pattern + '  <= ' + $_.Hit } else { 'MISS ' + $_.Pattern } })
                    [IO.File]::WriteAllLines((Join-Path $res 'wait-markers.txt'), [string[]]$rep)
                    if ($missing.Count -gt 0) {
                        $why = 'timeout'
                        if ($ctx.Proc.HasExited) { $why = "server exited (code $($ctx.Proc.ExitCode))" }
                        throw ("{0}/{1} marker(s) not found ({2}): {3}" -f $missing.Count, $pending.Count, $why, (($missing | ForEach-Object { $_.Pattern }) -join ' ; '))
                    }
                    Set-GGStage 'PASS' ("{0}/{0} marker(s) found" -f $pending.Count)
                })
        }

    } finally {
        if ($ctx.Proc) {
            [void](Invoke-GGStage 'shutdown' {
                    $g = $ctx.Proc
                    if ($ctx.Rcon) { $ctx.Rcon.Dispose(); $ctx.Rcon = $null }
                    if ($g.HasExited) {
                        $code = $g.ExitCode
                        if (-not $ctx.Booted) { Set-GGStage 'SKIP' "server died during boot (exit $code), see boot stage" }
                        elseif ($ctx.ExpectStop -and $code -eq 0) { Set-GGStage 'PASS' 'stopped by test command' }
                        else { Set-GGStage 'FAIL' "server died after booting (exit $code), before the test finished; see the end of logs/latest.log" }
                    } elseif (-not $ctx.Booted) {
                        Stop-GGTree $g.Id
                        [void]$g.WaitForExit(15000)
                        Set-GGStage 'SKIP' 'boot did not finish: JVM killed'
                    } else {
                        try { $g.WriteLine('stop') } catch {}
                        if (-not $g.WaitForExit(30000)) {
                            Stop-GGTree $g.Id
                            [void]$g.WaitForExit(15000)
                            Set-GGStage 'WARN' 'did not stop within 30s, force-killed'
                        } elseif ($g.ExitCode -ne 0) {
                            Set-GGStage 'WARN' ("stopped, exit code {0}" -f $g.ExitCode)
                        } else {
                            Set-GGStage 'PASS' 'clean stop (exit 0)'
                        }
                    }
                    $g.CloseLogs()
                    Set-GGSlotState $null $false
                })
            # KubeJS script errors only exist in its own logs (`/kubejs errors server` needs a player, RCON has none).
            [void](Invoke-GGStage 'kubejs-errors' { Invoke-GGKubeJsCheck $inst $res })
            # a restarted run's first boot has its own KubeJS logs (moved to results\server\phase1\ before the second launch)
            if ($ctx.Phase1Logs) { [void](Invoke-GGStage 'kubejs-errors-phase1' { Invoke-GGKubeJsCheck (Join-Path $res 'phase1') (Join-Path $res 'phase1') }) }
        }
        Save-GGInstanceResults $inst $res
    }
}
