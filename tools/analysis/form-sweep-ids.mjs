// The multiblocks our startup scripts register, grouped by era folder, for the forming sweep (gg_test_form_sweep).
//   node tools/analysis/form-sweep-ids.mjs [--write | --check]
// Source: the pack's scripts run in Node (lib/kubejs_static.mjs), machines of kind 'multiblock'. --write rewrites
// tools/test/overlay/kubejs/config/gg_test_form_sweep_ids.json; --check exits 1 when that file is stale; no flag prints it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runPackScripts } from './lib/kubejs_static.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
export const IDS_FILE = path.join(repo, 'tools', 'test', 'overlay', 'kubejs', 'config', 'gg_test_form_sweep_ids.json');

// folders in progression order; any other folder follows alphabetically
const ORDER = ['steam', 'lv', 'mv', 'hv', 'ev', 'iv', 'luv', 'zpm', 'uv', 'uhv', 'uev', 'uiv', 'uxv'];

export function eraOf(file) {
  const m = /startup_scripts[\\/]grindless[\\/]([^\\/]+)[\\/]/.exec(String(file));
  return m ? m[1] : 'other';
}

export function buildIds(packDir = path.join(repo, 'pack')) {
  const run = runPackScripts(packDir);
  const eras = {};
  for (const m of run.registry.machines.values()) {
    if (m.kind !== 'multiblock') continue;
    (eras[eraOf(m.file)] = eras[eraOf(m.file)] || []).push(m.id);
  }
  const names = Object.keys(eras).sort((a, b) => {
    const ia = ORDER.indexOf(a);
    const ib = ORDER.indexOf(b);
    if (ia >= 0 || ib >= 0) return (ia < 0 ? 999 : ia) - (ib < 0 ? 999 : ib);
    return a < b ? -1 : 1;
  });
  const out = {
    _doc: 'Generated by tools/analysis/form-sweep-ids.mjs --write: every multiblock the pack\'s startup scripts register, by script folder. Do not edit.',
    // an id that only forms somewhere else (a dimension, inside a cleanroom): { "gtceu:id": { "dimension": "ns:key", "reason": "..." } }
    where: {},
    eras: {},
  };
  for (const n of names) out.eras[n] = eras[n].slice().sort();
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const fresh = buildIds();
  if (args.includes('--check')) {
    // `where` is hand-kept: only the generated part must match
    const have = JSON.parse(fs.readFileSync(IDS_FILE, 'utf8'));
    const same = JSON.stringify(have.eras) === JSON.stringify(fresh.eras);
    console.log(`form-sweep-ids: ${same ? 'up to date' : 'STALE, run --write'}`);
    process.exit(same ? 0 : 1);
  } else if (args.includes('--write')) {
    let where = {};
    if (fs.existsSync(IDS_FILE)) where = JSON.parse(fs.readFileSync(IDS_FILE, 'utf8')).where || {};
    fresh.where = where;
    fs.writeFileSync(IDS_FILE, JSON.stringify(fresh, null, 1) + '\n');
    const n = Object.values(fresh.eras).reduce((s, a) => s + a.length, 0);
    console.log(`written ${n} ids in ${Object.keys(fresh.eras).length} eras`);
  } else {
    console.log(JSON.stringify(fresh, null, 1));
  }
}
