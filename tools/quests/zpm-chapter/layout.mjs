export function place(quests) {
  return quests.map((q) => {
    const l = LAYOUT[q.key];
    if (!l) throw new Error('no layout for quest ' + q.key);
    return { ...q, x: l[0], y: l[1], deps: l[2] || q.deps };
  });
}
